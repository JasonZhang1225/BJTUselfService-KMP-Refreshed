#!/usr/bin/env python3
"""Bundle release-note change sections for offline use. Run --check in CI."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'multiplatform/shared/src/commonMain/kotlin/team/bjtuss/bjtuselfservice/shared/update/BundledChangelog.kt'


def kotlin_string(value):
    return json.dumps(value, ensure_ascii=False).replace('$', '\\$')


def generate():
    releases = []
    for path in (ROOT / 'docs/releases').glob('*.md'):
        text = path.read_text()
        sections = []
        for title in ('新增', '优化', '修复'):
            matches = re.findall(rf'^## {title}\n\n(.*?)(?=^## |\Z)', text, re.M | re.S)
            if len(matches) != 1:
                raise ValueError(f'{path.name}: expected one {title} section')
            items = []
            for line in matches[0].splitlines():
                if line.strip().startswith('- '):
                    item = line.strip()[2:]
                    item = re.sub(r'\[([^]]+)\]\([^)]+\)', r'\1', item)
                    items.append(item.replace('**', '').replace('`', ''))
            if not items:
                raise ValueError(f'{path.name}: empty {title} section')
            sections.append((title, items))
        tag = path.stem
        label = tag.removeprefix('v')
        if tag.startswith('debug-'):
            label = tag.removeprefix('debug-') + '（调试构建）'
        elif tag == 'v1.0.0-gitee-test':
            label += '（更新源测试）'
        elif tag == 'v2.0.0-KMP':
            label += '（发布草稿）'
        version = tuple(map(int, re.search(r'(\d+)\.(\d+)\.(\d+)', tag).groups()))
        releases.append((version, tag.startswith('v'), tag, label, sections))
    releases.sort(reverse=True)
    lines = ['// Generated by scripts/sync-bundled-changelog.py; edit docs/releases instead.',
             'package team.bjtuss.bjtuselfservice.shared.update', '',
             'internal data class ChangelogSection(val title: String, val items: List<String>)',
             'internal data class ChangelogRelease(val tag: String, val label: String, val sections: List<ChangelogSection>)',
             '', 'internal object BundledChangelog {', '    val entries: List<ChangelogRelease> = listOf(']
    for _, _, tag, label, sections in releases:
        lines.append(f'        ChangelogRelease({kotlin_string(tag)}, {kotlin_string(label)}, listOf(')
        for title, items in sections:
            lines.append(f'            ChangelogSection({kotlin_string(title)}, listOf(')
            lines += [f'                {kotlin_string(item)},' for item in items]
            lines.append('            )),')
        lines.append('        )),')
    lines += ['    )', '}', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            raise SystemExit('Bundled changelog is stale; run python3 scripts/sync-bundled-changelog.py')
        print('All release sections and bundled changelog are in sync.')
    else:
        OUTPUT.write_text(content)
